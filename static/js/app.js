// --- Service inquiry form (present on /contact and each service page) -------
const inquiryForm = $("#inquiryForm");
if (inquiryForm) {
  inquiryForm.addEventListener("submit", async (e) => {
    e.preventDefault();
    const form = e.currentTarget;
    const status = $("#formStatus");
    status.className = "form-status";
    status.textContent = lang === "hi" ? "भेजा जा रहा है…" : "Submitting…";
    const payload = Object.fromEntries(new FormData(form).entries());
    payload.language = lang;
    try {
      const res = await fetch("/api/inquiry", {
        method:"POST", headers:{"Content-Type":"application/json"}, body:JSON.stringify(payload)
      });
      const data = await res.json();
      if (!res.ok || !data.ok) throw new Error(data.message || "Request failed");
      status.className = "form-status success";
      status.textContent = lang === "hi" ? "आपका सेवा अनुरोध सफलतापूर्वक भेज दिया गया है।" : "Your service inquiry was submitted successfully.";
      form.reset();
    } catch (err) {
      status.className = "form-status error";
      status.textContent = err.message || (lang === "hi" ? "कृपया दोबारा प्रयास करें।" : "Please try again.");
    }
  });
}

// --- Chatbot widget (present on every page via partials/chat_widget.html) ---
const overlay = $("#chatOverlay");
if (overlay) {
  function openChat() { overlay.classList.add("open"); overlay.setAttribute("aria-hidden","false"); setTimeout(() => $("#chatInput")?.focus(), 100); }
  function closeChat() { overlay.classList.remove("open"); overlay.setAttribute("aria-hidden","true"); }
  $$("[data-chat-open]").forEach(btn => btn.addEventListener("click", openChat));
  $("#chatClose")?.addEventListener("click", closeChat);
  overlay.addEventListener("click", e => { if (e.target === overlay) closeChat(); });
  document.addEventListener("keydown", e => { if (e.key === "Escape") closeChat(); });

  function addBubble(text, type="bot") {
    const el = document.createElement("div");
    el.className = `chat-bubble ${type}`;
    el.textContent = text;
    $("#chatMessages").appendChild(el);
    $("#chatMessages").scrollTop = $("#chatMessages").scrollHeight;
    return el;
  }

  $("#chatForm")?.addEventListener("submit", async (e) => {
    e.preventDefault();
    const input = $("#chatInput");
    const message = input.value.trim();
    if (!message) return;
    addBubble(message, "user");
    input.value = "";
    const typing = addBubble(lang === "hi" ? "सोच रहा हूँ…" : "Thinking…", "bot typing");
    try {
      const res = await fetch("/api/chat", {
        method:"POST", headers:{"Content-Type":"application/json"},
        body:JSON.stringify({message})
      });
      const data = await res.json();
      typing.remove();
      addBubble(data.ok ? data.answer : (data.message || "Unable to answer right now."), "bot");
    } catch {
      typing.remove();
      addBubble(lang === "hi" ? "अभी चैट उपलब्ध नहीं है। कृपया सेवा अनुरोध भेजें।" : "Chat is unavailable right now. Please submit a service inquiry.", "bot");
    }
  });
}

